export function englishLocality(name) {
  if (PLACES.has(name)) return PLACES.get(name);
  const coast = name.match(/^(.+)海上保安(監)?部$/u);
  if (coast && JAPAN_COAST_GUARD.has(coast[1]))
    return `${JAPAN_COAST_GUARD.get(coast[1])} Coast Guard Office`;
  return name.replace(/\(([^)]+)\)/g, (match, district) =>
    KOREAN_DISTRICTS.has(district)
      ? `(${KOREAN_DISTRICTS.get(district)})`
      : match,
  );
}
