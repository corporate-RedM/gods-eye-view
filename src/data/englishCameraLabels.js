export function englishAsianCameraName(name) {
  if (CAMERA_NAMES.has(name)) return CAMERA_NAMES.get(name);
  // Only road-shaped labels: do not rewrite characters inside proper names.
  if (
    !/^(國道\d+號|台\d|中\d+線|\d+線|臨\d+便道|國五蘇澳交流道|高港高架)/u.test(
      name,
    )
  )
    return name;
  let text = name
    .replace(/國道(\d+)號/g, 'National Freeway $1 ')
    .replace(/台(\d+)臨(\d+)線/g, 'Provincial Highway $1, Temporary Route $2 ')
    .replace(
      /台(\d+)([甲乙丙丁戊己庚])線?/g,
      (_, road, suffix) => `Provincial Highway ${road}${ROUTE_SUFFIX[suffix]} `,
    )
    .replace(/台(\d+)線/g, 'Provincial Highway $1 ')
    .replace(/中(\d+)線/g, 'Taichung Route $1 ')
    .replace(/^(\d+)線/g, 'County Highway $1 ')
    .replace(/臨(\d+)便道/g, ' Temporary Access Road $1 ')
    .replace(/[（]/g, '(')
    .replace(/[）]/g, ')');
  for (const [local, english] of ROAD_TERMS)
    text = text.replaceAll(local, ` ${english} `);
  text = text.replace(
    /\b([NSWE])\b/g,
    (_, direction) =>
      ({ N: 'northbound', S: 'southbound', W: 'westbound', E: 'eastbound' })[
        direction
      ],
  );
  return text
    .replace(/(\d)[Kk]\+/g, '$1 km + ')
    .replace(/\s+/g, ' ')
    .replace(/\(\s+/g, '(')
    .replace(/\s+\)/g, ')')
    .trim();
}

